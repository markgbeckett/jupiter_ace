: 8TOFLOAT
    DUP 128 > SWAP
    UFLOAT
    ROT IF 256.0 F-
    THEN
;

: GETTEMP
    LM_SETUP LM_READ
    SWAP 8TOFLOAT
    ROT 128 AND IF 0.5 F+ THEN
    CR ." Temperature (deg. C) " F. CR
;

