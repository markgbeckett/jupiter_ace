: TEMP_TO_LCD ( -- )
    ( DISPLAY TEMP ON LCD )
    ( ASSUME BASE = DECIMAL )
    MSG_TEMP LCD_PRINT

    1000 PAUSE
    
    LM_SETUP DROP
    
    LM_READ ( S: FL TEMP_DP TEMP )

    1000 PAUSE

