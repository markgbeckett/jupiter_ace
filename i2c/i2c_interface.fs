	-1
    ELSE
	0
    THEN
;

: LCD_PRINT_NUM ( NUM -- )
    16->32 ( CONVERT TO LONG INTEGER )
    <# # # #> ( S: LEN ADDR )
    SWAP 1- ( S: ADDR-1 LEN )
    SWAP OVER ( S: ADDR-1 LEN ADDR-1 )
    C! ( STORE LEN )

    LCD_PRINT ( INTEGER PART OF TEMP )
;

