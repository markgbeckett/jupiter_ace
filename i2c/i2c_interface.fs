: LCD_SEND_4_BITS ( VALUE -- )
    LCD_BL_STATE OR ( PRESERVE BACKLIGHT )
    DUP
    LCD_MASK_E OR
    I2C_WRITE DROP
    I2C_WRITE DROP
;

: LCD_SEND_NIBBLE ( VALUE -- )
    ( SEND HIGH NIBBLE OF VALUE )
    F0 AND
    LCD_SEND_4_BITS
;

: LCD_SEND_4 ( VALUE MODE -- )
    ( SEND VALUE AS TWO 4-BIT NIBBLES )
    ( MODE: 0 = CMD ; 1 = DATA )
    OVER
    F0 AND ( HIGH NIBBLE OF VALUE )
    OVER IF ( MODE = DATA )
	LCD_MASK_RS OR
    THEN
    
    LCD_SEND_4_BITS
    
    ( S: VALUE MODE )
    SWAP
    0F AND 10 * ( LOW NIBBLE OF VALUE )

    SWAP IF ( MODE = DATA )
	LCD_MASK_RS OR
    THEN
    
    LCD_SEND_4_BITS
;

: LCD_SEND ( VALUE MODE -- )
    DISP_ADDR I2C_OPEN DROP
    LCD_SEND_4
    I2C_STOP
;

: LCD_INIT
    ( BACKLIGHT ON )
    LCD_BACKLIGHT LCD_BL_STATE !

    LCD_FUNC LCD_8BITMODE OR LCD_SEND_NIBBLE

    LCD_FUNC LCD_4BITMODE OR LCD_SEND_NIBBLE

    LCD_FUNC LCD_2LINE OR
    LCD_CMD_MODE LCD_SEND

    LCD_ENTRYMODE LCD_ELEFT OR LCD_ENTRY_S_DEC OR
    LCD_CMD_MODE LCD_SEND

    LCD_CTRL LCD_DISP_ON OR LCD_CUR_ON OR LCD_BLINK OR
    LCD_CMD_MODE LCD_SEND
;
