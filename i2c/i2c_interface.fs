: LCD_PRINT ( STR -- )
    DISP_ADDR I2C_OPEN DROP

    ( ITERATE OVER STRING )
    DUP 1+ SWAP C@ ( S: START LEN )
    OVER + SWAP DO ( S: END START )
	I C@
	LCD_DATA_MODE LCD_SEND
    LOOP    

    I2C_CLOSE
;

:  16->32 ( N -- D )
