: PAUSE
    0 DO LOOP
;

    
: LCD_SEND_4_BITS ( VALUE -- )
    LCD_BL_STATE @ OR ( PRESERVE BACKLIGHT )

    DUP ( REPLICATE VALUE TO MAKE LATCHING EASIER )
    LCD_MASK_E OR I2C_WRITE DROP ( LATCH )
    I2C_WRITE DROP ( NO LATCH )
;

: LCD_SEND_NIBBLE ( VALUE -- )
    ( SEND ONE NIBBLE - USED DURING INIT )
    F0 AND ( ZERO STATS )
    LCD_SEND_4_BITS
;

: LCD_SEND ( VALUE MODE -- )
    ( SEND VALUE AS TWO 4-BIT NIBBLES )
    ( MODE: 0 = CMD ; 1 = DATA )
    OVER
    F0 AND ( HIGH NIBBLE OF VALUE )
    OVER LCD_DATA_MODE = IF ( MODE = DATA )
	LCD_MASK_RS OR
    THEN
    
    LCD_SEND_4_BITS
    
    ( S: VALUE MODE )
    SWAP
    0F AND 10 * ( LOW NIBBLE OF VALUE )

    SWAP LCD_DATA_MODE = IF ( MODE = DATA )
	LCD_MASK_RS OR
    THEN
    
    LCD_SEND_4_BITS
;

: LCD_INIT ( INITIALISE/ RESET DISPLAY )
    DISP_ADDR I2C_OPEN DROP

    ( SOFTWARE INITIALISATION SEQUENCE )
    30 LCD_SEND_NIBBLE
    1 I2C_DELAY
    30 LCD_SEND_NIBBLE
    1 I2C_DELAY
    30 LCD_SEND_NIBBLE
    1 I2C_DELAY
    20 LCD_SEND_NIBBLE
    1 I2C_DELAY
    
    ( ENABLE BACKLIGHT )
    LCD_BACKLIGHT LCD_BL_STATE !

    LCD_FUNCTION_SET ( CONFIGURE FUNCTION SET FIRST )
    LCD_2LINE OR ( TWO LINE DISPLAY )
    LCD_FONT_507 OR ( 5X7 FONT ONLY FOR TWO LINES )
    LCD_CMD_MODE LCD_SEND

    LCD_DISP_MODE ( ACTIVATE DISPLAY )
    LCD_BLINK_ON OR
    LCD_CURS_ON OR
    LCD_DISP_ON OR
    LCD_CMD_MODE LCD_SEND
    
    LCD_ENTRY_MODE ( SET ENTRY MODE )
    LCD_NO_SHIFT OR ( CURSOR ADVANCES RIGHT )
    LCD_ENTRY_C_INC OR
    LCD_CMD_MODE LCD_SEND

    I2C_CLOSE
;

: LCD_BL_OFF ( DISABLE BACKLIGHT )
    DISP_ADDR I2C_OPEN DROP
    
    ( NEW STATE ALSO STORED IN LCD_BL_STATE )
    LCD_NO_BACKLIGHT DUP LCD_BL_STATE !
    I2C_WRITE

    I2C_CLOSE
;

: LCD_BL_ON ( ENABLE BACKLIGHT )
    DISP_ADDR I2C_OPEN DROP

    ( NEW STATE ALSO STORED IN LCD_BL_STATE )
    LCD_BACKLIGHT DUP LCD_BL_STATE !
    I2C_WRITE

    I2C_CLOSE
;

: LCD_SET_CURSOR ( COL ROW -- )
    DISP_ADDR I2C_OPEN DROP

    40 * + ( WORK OUT OFFSET )
    LCD_DDRAM OR ( ADDRESS DISP RAM )
    LCD_CMD_MODE LCD_SEND

    I2C_CLOSE
;

: LCD_SHIFT ( DIRN -- )
    ( SHIFT DISPLAY LEFT ONE CELL )
    DISP_ADDR I2C_OPEN DROP

    LCD_DISP_SHIFT
    SWAP IF
	LCD_SHIFT_LEFT OR
    ELSE
	LCD_SHIFT_RIGHT OR
    THEN
    LCD_DISP_MOVE OR
    
    LCD_CMD_MODE LCD_SEND
    
    I2C_CLOSE
;

: LCD_MOVE_CURS ( DIRN -- )
    ( SHIFT DISPLAY LEFT ONE CELL )
    DISP_ADDR I2C_OPEN DROP

    LCD_DISP_SHIFT
    SWAP IF
	LCD_SHIFT_LEFT OR
    ELSE
	LCD_SHIFT_RIGHT OR
    THEN
    LCD_CURS_MOVE OR
    
    LCD_CMD_MODE LCD_SEND
    
    I2C_CLOSE
;

: LCD_CLS ( -- )
    ( CLEAR DISPLAY AND RESET CURSOR TO TOP-LEFT )
    ( ALSO CANCEL ANY DISPLAY SHIFT )
    DISP_ADDR I2C_OPEN DROP

    LCD_CLS_CMD LCD_CMD_MODE LCD_SEND

    I2C_CLOSE
;

: LCD_HOME ( -- )
    ( RESET CURSOR TO TOP-LEFT OF DISPLAY )
    ( ALSO CANCEL ANY DISPLAY SHIFT )
    DISP_ADDR I2C_OPEN DROP

    LCD_HOME_CMD LCD_CMD_MODE LCD_SEND

    I2C_CLOSE
;


