( I2C INTERFACE LOW-LEVEL )
HEX
20 INTEGER I2C_PORT
81 INTEGER I2C_QUIES
0 VARIABLE I2C_BANK
01 INTEGER SCLBIT
80 INTEGER SDABIT
: I2C_RDPORT I2C_PORT INP ;
: I2C_WRPORT DUP I2C_PORT OUTP
  I2C_BANK ! ;
: I2C_SCL_LO I2C_BANK @ SCLBIT
  FF XOR AND I2C_WRPORT ;
: I2C_SCL_HI I2C_BANK @ SCLBIT
  OR I2C_WRPORT ;
: I2C_SDA_LO I2C_BANK @ SDABIT
  FF XOR AND I2C_WRPORT ;  -->

