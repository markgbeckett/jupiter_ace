: SLA 2 * 100 /MOD SWAP ;
: I2C_READ 0 8 0 DO 2 *
  I2C_SDA_HI I2C_SCL_HI
  I2C_WAIT I2C_RDPORT SDABIT
  AND IF 1 + THEN I2C_SCL_LO
  LOOP SWAP IF I2C_SDA_LO ELSE
  I2C_SDA_HI THEN I2C_SCL_HI
  1 I2C_DELAY I2C_SCL_LO
  I2C_SDA_HI ;
                           -->

